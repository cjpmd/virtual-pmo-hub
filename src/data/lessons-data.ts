const dateFor = (phaseId: string, index: number) => {
  const base: Record<string, string> = {
    "phase-1": "2025",
    "phase-2": "2025",
    "phase-3": "2026",
    "phase-4": "2026",
    "phase-5": "2026",
    "phase-6": "2026",
  };
  const month = String(((index * 5) % 12) + 1).padStart(2, "0");
  const day = String(((index * 7) % 27) + 1).padStart(2, "0");
  return `${day}/${month}/${base[phaseId] ?? "2026"}`;
};

