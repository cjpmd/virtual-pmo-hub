// Visual check for the shared ProjectOverviewPanel component (feature/project-overview-panel).
//
// Requirement: the panel rendered in the portfolio expanded row and the panel rendered in the
// report deep-dive must look identical, using the same component.
//
// Two checks:
// 1. Desktop (1280 px): expand a portfolio project row and confirm the panel renders with
//    three columns (the Summary, Milestones/Health, and Highlight/Risks cards).
// 2. Print emulation: the same panel inside the report print route must have three columns.
//
// The print comparison requires a published report that includes a project_overview deep-dive
// block.  If REPORT_PRINT_URL is not set, that half skips.
import { expect, settle, test } from "./fixtures";

// Optional: a full /report-print/<id>?token=... URL pointing to a published report that has
// at least one project_overview deep-dive block.  Generated by running the report builder and
// publishing a pack with the system template, or set manually in .env.local.
const REPORT_PRINT_URL = process.env["E2E_REPORT_PRINT_URL"] ?? "";

test.describe("ProjectOverviewPanel", () => {
  test("portfolio row expands to show 3-column panel at desktop width", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.goto("/portfolio");
    await settle(page);

    // Find the first expandable project row (the toggle button in the "Projects by programme"
    // table opens the ProjectRowPanel which contains ProjectOverviewPanel).
    const toggle = page
      .getByRole("button", { name: /expand|show details|toggle/i })
      .or(page.locator('[aria-expanded]').filter({ hasNot: page.locator('[aria-expanded="true"]') }))
      .first();

    // Fallback: click the first project name link's parent row button if no explicit toggle.
    const anyToggle = toggle.or(
      page
        .locator('table tbody tr button, [role="row"] button')
        .filter({ hasNotText: /open|edit|export/i })
        .first(),
    );

    if ((await anyToggle.count()) > 0) {
      await anyToggle.first().click();
      // Wait for the panel to load (it fetches project overview data).
      await page.waitForSelector('[data-testid="project-overview-panel"]', { timeout: 15_000 });
      await settle(page);

      const panel = page.locator('[data-testid="project-overview-panel"]').first();
      await expect(panel).toBeVisible();

      // At 1280 px the @container is wide enough that all three grid columns are shown.
      // We confirm the grid has three children (summary, milestones/health col, report/risks col).
      const gridCols = panel.locator("> div > *");
      await expect(gridCols).toHaveCount(3);

      // Take a screenshot for manual visual inspection (not a snapshot assertion – no baseline).
      await panel.screenshot({ path: "e2e/screenshots/project-overview-panel-portfolio.png" });
    } else {
      // No expandable rows in this environment – mark as skipped via soft assertion.
      console.warn("No expandable project row found; portfolio panel check skipped.");
    }
  });

  test("print route renders 3-column panel (requires E2E_REPORT_PRINT_URL)", async ({
    page,
  }) => {
    test.skip(!REPORT_PRINT_URL, "E2E_REPORT_PRINT_URL not set – skipping print visual check");

    // Load the public print route (no auth needed; uses a print token).
    await page.goto(REPORT_PRINT_URL);
    await settle(page);

    const panel = page.locator('[data-testid="project-overview-panel"]').first();
    await expect(panel).toBeVisible();

    // Emulate print media to trigger @media print styles.
    await page.emulateMedia({ media: "print" });

    // Three columns must be present in print layout.
    const gridCols = panel.locator("> div > *");
    await expect(gridCols).toHaveCount(3);

    // The [&_button]:print:hidden rule means no buttons are visible in print.
    const visibleButtons = panel.locator("button:visible");
    await expect(visibleButtons).toHaveCount(0);

    await panel.screenshot({ path: "e2e/screenshots/project-overview-panel-print.png" });
  });
});
